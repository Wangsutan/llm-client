#pragma once

#include <stddef.h>

// 单次回答的字符上限。模型循环输出、或者前端已经断开但上游还在吐 token 时，
// 三处累积串（fullAnswer / answer / pending）都没有上界，长回答叠上历史会把最大
// 连续块啃穿。到上限就主动收工，前端仍能拿到已生成的部分。
constexpr size_t LLM_ANSWER_MAX = 65536;

// 板上只保留回答的前缀（完整文本在浏览器里，板子只需要"有没有内容"和"多长"）。
// 摘要接口要靠它拿到模型返回的摘要正文，2KB 够用（提示词要求不超过 200 字）。
constexpr size_t LLM_KEEP_MAX = 2048;

// 请求处理的工作区：静态分配（.bss），开机即占、不经过堆、地址固定。
// 进来的明文 JSON 整块放在这里（解压目标也是它），所以它同时就是"单请求明文上限"。
// 之前是每轮 malloc 一块，可用最大连续块只有 40-65KB 且随碎片浮动；换成固定工作区后
// 上限变成确定值，短对话也不再制造/打碎大块。
constexpr size_t WORK_BUF_SIZE = 48 * 1024;
